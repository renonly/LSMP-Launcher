const { contextBridge, ipcRenderer } = require("electron");
const inv = (ch) => (...a) => ipcRenderer.invoke(ch, ...a);

contextBridge.exposeInMainWorld("lsmp", {
  session: inv("auth:session"),
  login: inv("auth:login"),
  register: inv("auth:register"),
  logout: inv("auth:logout"),
  play: inv("game:play"),
  stop: inv("game:stop"),
  sync: inv("game:sync"),
  uninstall: inv("game:uninstall"),
  on: (ch, fn) => ipcRenderer.on(`game:${ch}`, (_e, d) => fn(d)),
  config: inv("config"),
  getSettings: inv("settings:get"),
  setSettings: inv("settings:set"),
  resetSettings: inv("settings:reset"),
  status: inv("status:server"),
  packInfo: inv("pack:info"),
  stats: inv("stats"),
  news: inv("news"),
  shots: inv("shots:list"),
  showShot: inv("shots:show"),
  chooseBg: inv("bg:choose"),
  clearBg: inv("bg:clear"),
  detectJava: inv("java:detect"),
  chooseJava: inv("java:choose"),
  openGameDir: inv("shell:openGame"),
  openShots: inv("shell:openShots"),
  openData: inv("shell:openData"),
  openLog: inv("shell:openLog"),
  openExternal: inv("shell:external"),
  copy: (t) => ipcRenderer.send("clipboard:copy", t),
  win: (a) => ipcRenderer.send("win", a),
  // auto-update do launcher
  updateState: inv("update:state"),
  updateCheck: inv("update:check"),
  installUpdate: () => ipcRenderer.send("update:install"),
  onUpdate: (fn) => ipcRenderer.on("update:status", (_e, d) => fn(d)),
});
